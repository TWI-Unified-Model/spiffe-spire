package platform

import (
	"crypto"
	"crypto/ecdsa"
	"crypto/hpke"
	"crypto/x509"
	"errors"
	"fmt"
)

// Plugin is the TACRA Platform Plug-In. It runs inside the Attester TEE and
// is the only component that talks to the platform ABI (quote, RNG, keys).
type Plugin interface {
	// Name identifies the backend ("sev-snp", "tdx").
	Name() string

	// GenerateCEK creates an asymmetric Credential Encryption Key used in
	// Retrieval mode. alg is the CEK algorithm from
	// Initiate-Credential-Acquisition. The public half is bound into
	// Evidence; the private half unwraps the credential the CAS returns.
	GenerateCEK(alg EncryptionAlgorithm) (*KeyPair, error)

	// GenerateCSK creates an asymmetric Credential Signing Key used in
	// Enrollment mode. alg is the CSK algorithm from
	// Initiate-Credential-Acquisition. The public half is bound into
	// Evidence; the private half signs the CSR.
	GenerateCSK(alg SigningAlgorithm) (*KeyPair, error)

	// GenerateEvidence produces RATS Evidence: a hardware report whose
	// report data is the binding value (binding.go) over the freshness
	// element, the Target, the Relying Party and the subject (the CSR, or
	// CEKpub), so that Evidence, CSR and key are bound together.
	GenerateEvidence(req EvidenceRequest) (*Evidence, error)

	// LocalEpoch is an epoch identifier already held by the Attester.
	// Used when Freshness Kind is absent-epoch. Empty if the platform
	// does not keep an epoch.
	LocalEpoch() []byte

	// AttestationPublicKey is the AK that signs Evidence. Provision it to
	// the Verifier as a CoRIM trust anchor.
	AttestationPublicKey() *ecdsa.PublicKey
}

// KeyPair is a key generated by the plug-in.
//
// CEK is ECDH P-256, RSA-2048 or MLKEM768-P256 (an hpke.PrivateKey, for the
// hpke-base container). CSK is ECDSA P-256 or RSA-2048 and is used as a
// crypto.Signer for CSRs.
type KeyPair struct {
	Private crypto.PrivateKey
}

// Public returns the public half of the key pair: an hpke.PublicKey for an
// MLKEM768-P256 CEK, else the public key of the crypto.Signer.
func (k *KeyPair) Public() crypto.PublicKey {
	if k != nil {
		if h, ok := k.Private.(hpke.PrivateKey); ok {
			return h.PublicKey()
		}
	}
	s, err := k.Signer()
	if err != nil {
		return nil
	}
	return s.Public()
}

// CEKPub is CEKpub as the binding input carries it and the Secret Vault receives it: for an MLKEM768-P256 key
// (an hpke.PublicKey) the 1249-octet encapsulation key itself, which has no SubjectPublicKeyInfo form here; for
// any other key its DER SubjectPublicKeyInfo.
func CEKPub(pub crypto.PublicKey) ([]byte, error) {
	if h, ok := pub.(hpke.PublicKey); ok {
		return h.Bytes(), nil
	}
	return x509.MarshalPKIXPublicKey(pub)
}

// PublicPKIX returns the PKIX/SPKI encoding of the public key.
func (k *KeyPair) PublicPKIX() ([]byte, error) {
	pub := k.Public()
	if pub == nil {
		return nil, errors.New("platform: nil key pair")
	}
	return x509.MarshalPKIXPublicKey(pub)
}

// PrivatePKCS8 returns the PKCS#8 encoding of the private key.
func (k *KeyPair) PrivatePKCS8() ([]byte, error) {
	if k == nil || k.Private == nil {
		return nil, errors.New("platform: nil key pair")
	}
	return x509.MarshalPKCS8PrivateKey(k.Private)
}

// Signer returns the private key as a crypto.Signer (for CSR generation).
func (k *KeyPair) Signer() (crypto.Signer, error) {
	if k == nil || k.Private == nil {
		return nil, errors.New("platform: nil key pair")
	}
	s, ok := k.Private.(crypto.Signer)
	if !ok {
		return nil, fmt.Errorf("platform: %T is not a crypto.Signer", k.Private)
	}
	return s, nil
}

// BoundKeyUse says whether the key confirmed in Evidence is a CEK or a CSK.
type BoundKeyUse int64

const (
	BoundKeyUseUnspecified BoundKeyUse = 0
	BoundKeyUseEncrypt     BoundKeyUse = 1 // CEK, Retrieval
	BoundKeyUseSign        BoundKeyUse = 2 // CSK, Enrollment
)

// FreshnessKind classifies Evidence freshness for one credential-acquisition
// exchange (draft-novak-rats-tacra). Values match caapi.v1.FreshnessKind.
type FreshnessKind int32

const (
	FreshnessKindUnspecified     FreshnessKind = 0
	FreshnessKindAbsentNone      FreshnessKind = 1
	FreshnessKindAbsentTimestamp FreshnessKind = 2
	FreshnessKindAbsentEpoch     FreshnessKind = 3
	FreshnessKindPresentNonce    FreshnessKind = 4
	FreshnessKindPresentEpoch    FreshnessKind = 5
)

// SigningAlgorithm is the CSK algorithm for Enrollment. Values match
// caapi.v1.SigningAlgorithm.
type SigningAlgorithm int32

const (
	SigningAlgorithmUnspecified SigningAlgorithm = 0
	SigningAlgorithmECDSAP256   SigningAlgorithm = 1
	SigningAlgorithmRSA2048     SigningAlgorithm = 2
)

// EncryptionAlgorithm is the CEK algorithm for Retrieval. Values match
// caapi.v1.EncryptionAlgorithm.
type EncryptionAlgorithm int32

const (
	EncryptionAlgorithmUnspecified  EncryptionAlgorithm = 0
	EncryptionAlgorithmECDHP256     EncryptionAlgorithm = 1
	EncryptionAlgorithmRSA2048      EncryptionAlgorithm = 2
	EncryptionAlgorithmMLKEM768P256 EncryptionAlgorithm = 3 // the hpke-base container's hybrid suite
)

// generateMLKEM768P256 makes a fresh MLKEM768-P256 CEK (the hybrid KEM of the hpke-base container).
func generateMLKEM768P256() (*KeyPair, error) {
	sk, err := hpke.MLKEM768P256().GenerateKey()
	if err != nil {
		return nil, fmt.Errorf("platform: generate MLKEM768-P256 key: %w", err)
	}
	return &KeyPair{Private: sk}, nil
}

// EvidenceRequest is the input to Plugin.GenerateEvidence.
type EvidenceRequest struct {
	// FreshnessKind selects how freshness is established. present-* kinds
	// bind FreshnessHandle as eat_nonce; absent-* kinds carry no
	// Handle from Initiate-Credential-Acquisition.
	FreshnessKind FreshnessKind

	// FreshnessHandle is the nonce or epoch marker the binding covers.
	// Empty for absent-* Freshness Kinds (no Handle from
	// Initiate-Credential-Acquisition). 8 to 64 octets when present, the
	// bounds RFC 9711 sets for eat_nonce.
	FreshnessHandle []byte

	// BoundKey is CEKpub (Retrieval) or CSKpub (Enrollment); the binding
	// covers it, as CEKpub itself or inside the CSR.
	BoundKey crypto.PublicKey

	// CSR is the PKCS#10 request for Enrollment. Empty for Retrieval.
	CSR []byte

	// BoundKeyUse selects encrypt vs sign. If Unspecified, Enrollment is
	// inferred from a non-empty CSR and Retrieval otherwise.
	BoundKeyUse BoundKeyUse

	// Target is the Target of Initiate-Credential-Acquisition. The
	// back-ends bind it into Evidence (the binding input of the TACRA Binding).
	Target string
}

// Evidence is RATS Evidence ready to send over CAAPI.
type Evidence struct {
	// Token is the Evidence: the configfs-tsm report with the certificates of
	// the host, CBOR-encoded (TSMReportMediaTypeCBOR).
	Token []byte

	// MediaType is the type a Verifier dispatches the token on.
	MediaType string

	// Claims is a CBOR map, unsigned, of what the Relying Party needs to
	// recompute the binding value (the TSMClaim keys).
	Claims []byte
}

var (
	ErrInvalidFreshnessHandle         = errors.New("platform: Freshness Handle must be 8-64 bytes")
	ErrMissingBoundKey                = errors.New("platform: bound public key is required")
	ErrUnsupportedKey                 = errors.New("platform: bound key must be P-256 ECDSA or RSA-2048")
	ErrUnsupportedSigningAlgorithm    = errors.New("platform: unsupported signing algorithm")
	ErrUnsupportedEncryptionAlgorithm = errors.New("platform: unsupported encryption algorithm")
	ErrNilPlugin                      = errors.New("platform: nil plugin")
)

func resolveKeyUse(req EvidenceRequest) BoundKeyUse {
	if req.BoundKeyUse != BoundKeyUseUnspecified {
		return req.BoundKeyUse
	}
	if len(req.CSR) > 0 {
		return BoundKeyUseSign
	}
	return BoundKeyUseEncrypt
}
